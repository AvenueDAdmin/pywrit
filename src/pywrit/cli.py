def request(method, path, payload=None, key=None, token=None):
    headers = {"content-type": "application/json"}
    if key:
        headers["authorization"] = "Bearer " + key
    elif token:
        headers["authorization"] = token
    data = None if payload is None else json.dumps(payload).encode()
    req = urllib.request.Request(BASE + path, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=20) as resp:
            body = resp.read().decode()
            print(body)
            return 0
    except urllib.error.HTTPError as exc:
        print(exc.read().decode(), file=sys.stderr)
        return exc.code


def stream_cmd(args):
    """Tail the tenant audit log via the SSE stream, reconnecting on each
    long-poll expiry. Prints one line per receipt."""
    import time
    import urllib.parse

    key = args.key
    since = args.since
    deadline = None if args.timeout == 0 else time.time() + args.timeout
    try:
        while deadline is None or time.time() < deadline:
            params = {"apiKey": key, "timeout": "10", "replay": "20"}
            if since:
                params["since"] = since
            url = BASE + "/v1/receipts/stream?" + urllib.parse.urlencode(params)
            req = urllib.request.Request(url, method="GET")
            try:
                with urllib.request.urlopen(req, timeout=30) as resp:
                    data_lines = []
                    for raw in resp:
                        line = raw.decode("utf-8", "replace").rstrip("\n")
                        if line.startswith("data:"):
                            data_lines.append(line[5:].strip())
                        elif line == "" and data_lines:
                            try:
                                r = json.loads("".join(data_lines))
                            except json.JSONDecodeError:
                                data_lines = []
                                continue
                            ts = time.strftime("%H:%M:%S", time.localtime(r.get("createdAt", 0)))
                            print(f"{ts} {r.get('decision','?'):7} {r.get('verb','')} {r.get('target','')} "
                                  f"sponsor={r.get('sponsorId','')} agent={r.get('agentId','')} "
                                  f"id={r.get('receiptId','')}", flush=True)
                            since = r.get("receiptId", since)
                            data_lines = []
                        # ": ping" heartbeats and "id:"/"event:" lines are ignored
            except urllib.error.HTTPError as exc:
                print(exc.read().decode(), file=sys.stderr)
                return exc.code
            except (urllib.error.URLError, TimeoutError, ConnectionError) as exc:
                print(f"stream reconnecting: {exc}", file=sys.stderr)
                time.sleep(2)
    except KeyboardInterrupt:
        pass
    return 0


