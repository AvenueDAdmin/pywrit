def _recv_name(func):
    if isinstance(func, _ast.Attribute):
        v = func.value
        if isinstance(v, _ast.Name):
            return v.id.lower()
        if isinstance(v, _ast.Attribute):
            return v.attr.lower()
        if isinstance(v, _ast.Call):
            return _recv_name(v.func)
    return ""


def _root_name(func):
    while isinstance(func, _ast.Attribute):
        func = func.value
    return func.id.lower() if isinstance(func, _ast.Name) else ""


_READ_SQL = ("select", "with", "explain", "describe", "show", "pragma")


def _sql_is_write(node):
    """True unless the statement is clearly a read (SELECT/WITH/...)."""
    if not node.args:
        return True
    first = node.args[0]
    if isinstance(first, _ast.Constant) and isinstance(first.value, str):
        stmt = first.value.lstrip(" (").lower()
        return not stmt.startswith(_READ_SQL)
    return True


def _open_is_write(node):
    mode = None
    if len(node.args) >= 2 and isinstance(node.args[1], _ast.Constant):
        mode = node.args[1].value
    for kw in node.keywords:
        if kw.arg == "mode" and isinstance(kw.value, _ast.Constant):
            mode = kw.value.value
    return isinstance(mode, str) and any(c in mode for c in "wax+")


def _call_chain(func):
    """Dotted callee chain as lowercase strings, root first."""
    chain = []
    while isinstance(func, _ast.Attribute):
        chain.append(func.attr)
        func = func.value
    if isinstance(func, _ast.Name):
        chain.append(func.id)
    chain.reverse()
    return [c.lower() for c in chain]


def _has_shell_kwarg(node):
    """True if the call has shell=True."""
    for kw in node.keywords:
        if kw.arg != "shell":
            continue
        if isinstance(kw.value, _ast.Constant) and kw.value.value is True:
            return True
        if getattr(kw.value, "value", None) is True:
            return True
    return False


def _classify_call(node):
    func = node.func
    if isinstance(func, _ast.Name) and func.id == "open":
        return "file" if _open_is_write(node) else None
    if not isinstance(func, _ast.Attribute):
        return None
    chain = _call_chain(func)
    if not chain:
        return None
    name = chain[-1]
    recv = chain[-2] if len(chain) > 1 else ""
    root = chain[0]

    # Shell / command execution
    if root == "subprocess" and name in _SUBPROCESS_METHODS:
        if _has_shell_kwarg(node):
            return "shell"
    if root == "os" and name in _OS_SHELL_METHODS:
        return "shell"
    if name == "exec_command" and (root == "paramiko"
                                     or recv in ("ssh", "channel", "chan")):
        return "shell"

    # Filesystem
    if root == "os" and name in _OS_WRITES:
        return "file"
    if root == "shutil" and name in _SHUTIL_WRITES:
        return "file"
    if name in _PATH_METHODS:
        return "file"

    # Email
    if name in _EMAIL_METHODS:
        return "email"
    # SendGrid sg.client.mail.send.post()
    if name == "post" and "mail" in chain and "send" in chain:
        return "email"

    # AWS
    if name in _AWS_METHODS:
        return "aws"

    # Payments (Stripe, PayPal, Braintree, Square)
    if root in _PAYMENTS_HINTS and name in _PAYMENTS_METHODS:
        return "payments"

    # Twilio / SMS
    if name in _SMS_METHODS and (recv in _SMS_HINTS or root in _SMS_HINTS):
        return "sms"

    # Slack SDK and generic webhook variables (reuse http)
    if name in _SLACK_METHODS:
        return "http"
    if root in _WEBHOOK_HINTS and name in _HTTP_BARE:
        return "http"

    # Kubernetes
    if any(name.startswith(p) for p in ("create_namespaced_",
                                          "delete_namespaced_",
                                          "patch_namespaced_",
                                          "replace_namespaced_")):
        return "k8s"
    if (root in _K8S_HINTS or any(c in _K8S_HINTS for c in chain)) and \
            name in ("create", "delete", "patch", "replace", "apply"):
        return "k8s"

    # GitHub API
    if name in _GITHUB_METHODS or root == "github":
        return "github"

    # Push providers (Firebase / FCM)
    if name in _PUSH_METHODS and (recv in ("messaging", "fcm")
                                  or root in ("fcm", "firebase")):
        return "push"

    # Data stores
    if name in _REDIS_METHODS and (recv in _REDIS_HINTS or root in _REDIS_HINTS):
        return "db"
    if name in _MONGODB_METHODS:
        return "db"
    if name in _FIRESTORE_METHODS and (recv in _FIRESTORE_HINTS
                                         or root in _FIRESTORE_HINTS):
        return "db"

    # HTTP clients (checked before generic .save() / .delete() so
    # httpx.delete, urllib.request.urlopen, etc. are not mis-classified).
    if name in _HTTP_BARE:
        return "http"
    if name in _HTTP_HINTED and (recv in _HTTP_HINTS or root in _HTTP_HINTS):
        return "http"
    if name in _URLWRITE_METHODS and root in ("urllib", "request", "urllib2"):
        return "http"

    # Databases / ORM
    if name in _DB_BARE:
        if name in ("execute", "executemany", "executescript") \
                and not _sql_is_write(node):
            return None
        return "db"
    if name in _DB_HINTED:
        if recv in _DB_HINTS:
            return "db"
        # Django/model instance heuristic: .save() / .delete()
        if name in ("save", "delete") and recv not in _ORM_NON_HINTS:
            return "db"
        return None

    # Queue
    if name in _QUEUE_BARE:
        return "queue"
    if name in _QUEUE_HINTED and (recv in _QUEUE_HINTS or root in _QUEUE_HINTS):
        return "queue"

    # Crypto / web3
    if name in _WEB3_METHODS and (root in ("w3", "web3")
                                  or "contract" in chain):
        return "crypto"

    # Docker SDK
    if (root == "docker" or "containers" in chain) and name in _DOCKER_METHODS:
        return "docker"

    # FTP uploads
    if name in _FTP_STOR:
        return "ftp"

    # PagerDuty / Opsgenie alerts
    if name in _ALERT_METHODS and (recv in _ALERT_HINTS or root in _ALERT_HINTS):
        return "alert"

    return None


def _is_gate_call(node):
    func = node.func
    if isinstance(func, _ast.Name):
        return func.id in ("writ_check", "_writ_check")
    if isinstance(func, _ast.Attribute):
        return func.attr in ("writ_check", "_writ_check")
    return False


class _ScanVisitor(_ast.NodeVisitor):
    def __init__(self, src, filename):
        self.src = src
        self.filename = filename
        self.func_stack = []
        self.cls_stack = []
        self.sites = []
        self.gated = set()  # (func_name, func_lineno)

    def visit_ClassDef(self, node):
        self.cls_stack.append(node.name)
        self.generic_visit(node)
        self.cls_stack.pop()

    def visit_FunctionDef(self, node):
        self._visit_func(node)

    def visit_AsyncFunctionDef(self, node):
        self._visit_func(node)

    def _visit_func(self, node):
        self.func_stack.append(node)
        self.generic_visit(node)
        self.func_stack.pop()

    def visit_Call(self, node):
        if self.func_stack:
            func = self.func_stack[-1]
            if _is_gate_call(node):
                self.gated.add((func.name, func.lineno))
            kind = _classify_call(node)
            if kind:
                cls = self.cls_stack[-1] if self.cls_stack else ""
                try:
                    seg = _ast.get_source_segment(self.src, node) or ""
                except Exception:
                    seg = ""
                snippet = " ".join(seg.split())[:100]
                self.sites.append(_WriteSite(self.filename, func.name, cls,
                                             node.lineno, kind, snippet))
        self.generic_visit(node)


def _infer_action(func_name, kind):
    tokens = [t for t in func_name.lower().split("_") if t]
    if not tokens:
        return _KIND_FALLBACK_ACTION[kind]
    first = tokens[0]
    if first in _GENERIC_PREFIXES:
        if len(tokens) > 1:
            second = tokens[1]
            return _ACTION_SYNONYMS.get(second, second)
        return _KIND_FALLBACK_ACTION[kind]
    return _ACTION_SYNONYMS.get(first, first)


def _infer_domain(rel_path, cls_name):
    parts = [p for p in rel_path.parts[:-1]
             if p not in _SKIP_DIRS and not p.startswith((".", "_"))]
    if parts:
        return parts[0].lower().replace("-", "_")
    stem = rel_path.stem
    if stem not in _SKIP_FILES:
        return stem.lower().replace("-", "_")
    if cls_name:
        d = cls_name.lower().replace("service", "").replace("handler", "")
        return d or "app"
    return "app"


def infer_verb(rel_path, func_name, cls_name, kind):
    return "%s.%s" % (_infer_domain(rel_path, cls_name),
                      _infer_action(func_name, kind))


